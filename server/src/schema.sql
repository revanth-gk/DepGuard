CREATE TABLE IF NOT EXISTS accounts (
  id UUID PRIMARY KEY,
  username TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS accounts_username_idx ON accounts (LOWER(username));

CREATE TABLE IF NOT EXISTS auth_sessions (
  token_hash TEXT PRIMARY KEY,
  account_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS auth_sessions_account_idx ON auth_sessions (account_id);
CREATE INDEX IF NOT EXISTS auth_sessions_expiry_idx ON auth_sessions (expires_at);

CREATE TABLE IF NOT EXISTS scans (
  id UUID PRIMARY KEY,
  account_id UUID REFERENCES accounts(id) ON DELETE SET NULL,
  username TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('completed', 'partial')),
  scanned_at TIMESTAMPTZ NOT NULL,
  repositories_found INTEGER NOT NULL,
  repositories_scanned INTEGER NOT NULL,
  repositories_with_package_json INTEGER NOT NULL,
  manifests_scanned INTEGER NOT NULL,
  dependencies_checked INTEGER NOT NULL,
  vulnerable_occurrences INTEGER NOT NULL,
  unresolved_occurrences INTEGER NOT NULL,
  scan_errors INTEGER NOT NULL,
  report JSONB NOT NULL
);

CREATE INDEX IF NOT EXISTS scans_scanned_at_idx ON scans (scanned_at DESC);
CREATE INDEX IF NOT EXISTS scans_username_idx ON scans (LOWER(username));
ALTER TABLE scans ADD COLUMN IF NOT EXISTS account_id UUID REFERENCES accounts(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS scan_repositories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scan_id UUID NOT NULL REFERENCES scans(id) ON DELETE CASCADE,
  full_name TEXT NOT NULL,
  name TEXT NOT NULL,
  url TEXT NOT NULL,
  default_branch TEXT,
  archived BOOLEAN NOT NULL DEFAULT FALSE,
  status TEXT NOT NULL,
  manifest_count INTEGER NOT NULL,
  dependency_count INTEGER NOT NULL,
  vulnerable_count INTEGER NOT NULL,
  errors JSONB NOT NULL DEFAULT '[]'::jsonb,
  UNIQUE (scan_id, full_name)
);

CREATE INDEX IF NOT EXISTS scan_repositories_full_name_idx ON scan_repositories (LOWER(full_name));

CREATE TABLE IF NOT EXISTS scan_manifests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scan_id UUID NOT NULL REFERENCES scans(id) ON DELETE CASCADE,
  repository_id BIGINT NOT NULL REFERENCES scan_repositories(id) ON DELETE CASCADE,
  path TEXT NOT NULL,
  status TEXT NOT NULL,
  errors JSONB NOT NULL DEFAULT '[]'::jsonb,
  dependency_count INTEGER NOT NULL,
  UNIQUE (repository_id, path)
);

CREATE TABLE IF NOT EXISTS scan_dependencies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scan_id UUID NOT NULL REFERENCES scans(id) ON DELETE CASCADE,
  repository_id BIGINT NOT NULL REFERENCES scan_repositories(id) ON DELETE CASCADE,
  manifest_id BIGINT NOT NULL REFERENCES scan_manifests(id) ON DELETE CASCADE,
  package_name TEXT NOT NULL,
  declared_version TEXT NOT NULL,
  resolved_version TEXT,
  dependency_type TEXT NOT NULL,
  status TEXT NOT NULL,
  error TEXT,
  UNIQUE (manifest_id, package_name, dependency_type)
);

CREATE INDEX IF NOT EXISTS scan_dependencies_package_idx ON scan_dependencies (LOWER(package_name));
CREATE INDEX IF NOT EXISTS scan_dependencies_status_idx ON scan_dependencies (status);

CREATE TABLE IF NOT EXISTS scan_advisories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scan_id UUID NOT NULL REFERENCES scans(id) ON DELETE CASCADE,
  dependency_id BIGINT NOT NULL REFERENCES scan_dependencies(id) ON DELETE CASCADE,
  advisory_id TEXT NOT NULL,
  summary TEXT NOT NULL,
  severity TEXT NOT NULL,
  source_references JSONB NOT NULL DEFAULT '[]'::jsonb,
  published_at TIMESTAMPTZ,
  modified_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS scan_advisories_id_idx ON scan_advisories (advisory_id);
CREATE INDEX IF NOT EXISTS scan_advisories_severity_idx ON scan_advisories (severity);

CREATE TABLE IF NOT EXISTS scan_recommendations (
  id UUID PRIMARY KEY,
  account_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  scan_id UUID NOT NULL REFERENCES scans(id) ON DELETE CASCADE,
  package_name TEXT NOT NULL,
  current_version TEXT NOT NULL,
  suggestions JSONB NOT NULL,
  provider TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS scan_recommendations_scan_idx ON scan_recommendations (scan_id);
